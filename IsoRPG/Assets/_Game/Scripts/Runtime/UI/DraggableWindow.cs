using UnityEngine;
using UnityEngine.EventSystems;
using UnityEngine.UI;

namespace IsoRPG.UI
{
    /// <summary>
    /// Позволяет таскать окно мышью за верхнюю полосу.
    ///
    /// Окна у нас открываются по центру и там же остаются. Пока открыто одно,
    /// это незаметно; но сумка вместе с лавкой уже перекрывают друг друга, а
    /// сравнить цену с тем, что лежит в мешке, нужно именно одновременно.
    ///
    /// Тянем за полосу заголовка, а не за всё окно. Иначе промах мимо строки
    /// списка сдвигал бы окно, и попытка нажать на предмет превращалась бы в
    /// перетаскивание — ошибка, которую человек не понимает и повторяет.
    /// </summary>
    public sealed class DraggableWindow : MonoBehaviour,
        IBeginDragHandler, IDragHandler
    {
        /// <summary>Что двигаем. Она же панель, на которой мы висим.</summary>
        private RectTransform target;

        private Canvas canvas;

        /// <summary>
        /// Высота полосы заголовка, за которую разрешено тащить, в единицах
        /// интерфейса. Считается от видимого верха окна вниз.
        /// </summary>
        private float grip = 30f;

        /// <summary>
        /// На сколько видимый верх окна выступает над панелью: нарисованная
        /// рамка кладётся отдельным слоем СНАРУЖИ панели, и золотая кромка,
        /// за которую человек и хватается, оказывается выше её края.
        /// </summary>
        private float bleed;

        /// <summary>
        /// Тащим ли прямо сейчас. Нажатие ниже полосы заголовка окно не
        /// двигает вовсе — иначе промах мимо строки списка уводил бы окно, и
        /// попытка нажать на предмет превращалась бы в перетаскивание.
        /// </summary>
        private bool dragging;

        /// <summary>
        /// Точное положение окна при перетаскивании, до округления.
        ///
        /// Окно ставится на целый пиксель, но копить надо точно: округляй
        /// само накопление — и остаток от каждого мелкого сдвига пропадёт,
        /// окно начнёт отставать от курсора при медленном движении мыши.
        /// </summary>
        private Vector2 exact;

        /// <summary>
        /// Отступ окна от края экрана. Ноль — окно упирается вплотную.
        ///
        /// Раньше здесь было «оставим 48 пикселей на экране, чтобы окно можно
        /// было вернуть», то есть окно разрешалось увести за край почти
        /// целиком. Так делать незачем: в WoW у фреймов стоит
        /// SetClampedToScreen, и окно не уезжает за край ни на пиксель —
        /// а раз увести нельзя, то и возвращать нечего. Задача, под которую
        /// был написан запас, не существует.
        /// </summary>
        private const float ScreenPad = 0f;

        /// <summary>
        /// Порядок, с которого поднимаем взятое окно над соседями.
        ///
        /// Двадцать один — сразу над самым верхним окном в покое (настройки
        /// на двадцати) и заметно ниже подсказки (50) и экрана смерти (60):
        /// поднятое окно обязано перекрыть соседей, но не всплывающую
        /// подсказку о предмете, который в нём же и лежит.
        /// </summary>
        private const int FrontFrom = 21;

        /// <summary>
        /// Выше не поднимаемся. Досчитав до потолка, начинаем заново с
        /// двадцати двух — это всё равно выше любого окна в покое, так что
        /// сброс не виден; расходится лишь порядок между окнами, которые
        /// уже двигали.
        /// </summary>
        private const int FrontCap = 45;

        private static int front = FrontFrom;

        /// <summary>Углы окна. Поле, а не переменная: считаются каждый кадр.</summary>
        private readonly Vector3[] corners = new Vector3[4];

        public void Setup(RectTransform panel, float handleHeight, float overhang)
        {
            target = panel;
            grip = handleHeight;
            bleed = overhang;
            canvas = GetComponentInParent<Canvas>();
        }

        /// <summary>
        /// Попало ли нажатие в полосу заголовка.
        ///
        /// Считаем по точке, а не отдельным элементом-ручкой поверх окна.
        /// Ручка была бы проще, но её судьба целиком зависит от порядка
        /// детей: в uGUI указатель ищет цель сверху вниз, поэтому ручка
        /// обязана быть последней в списке — а окна собирают содержимое
        /// после того, как обвязка уже навешена, и любой элемент, добавленный
        /// позже, накрывает её и молча забирает все нажатия. Со стороны это
        /// выглядит как «перетаскивание не сделано», хотя код на месте.
        ///
        /// Точке же порядок безразличен: событие всплывает по иерархии от
        /// надписей и картинок, у которых своего перетаскивания нет, и
        /// доходит до панели в любом случае.
        /// </summary>
        private bool OnTitleBar(PointerEventData eventData)
        {
            if (!RectTransformUtility.ScreenPointToLocalPointInRectangle(
                    target, eventData.position, eventData.pressEventCamera, out var local))
                return false;

            Rect area = target.rect;

            // Видимый верх окна выше панели на вылет рамки.
            float top = area.yMax + bleed;

            return local.y <= top && local.y >= top - (grip + bleed);
        }

        public void OnBeginDrag(PointerEventData eventData)
        {
            if (target == null) return;

            dragging = OnTitleBar(eventData);
            if (!dragging) return;

            exact = target.anchoredPosition;

            // Взятое окно выходит поверх остальных. Это ожидаемо настолько,
            // что обратное читается как поломка: тянешь окно, а оно уезжает
            // под соседнее.
            //
            // Через sortingOrder, а не через SetAsLastSibling. Прежний вызов
            // не работал и работать не мог: каждое окно — корень СВОЕГО
            // холста, а холсты между собой упорядочены не иерархией, а
            // порядком сортировки. Окно честно становилось последним среди
            // своих детей, то есть среди самого себя, и продолжало уезжать
            // под соседа.
            BringToFront(canvas);
        }

        /// <summary>
        /// Поднять окно над соседними.
        ///
        /// Публичная и статическая, потому что зовут её из двух мест: отсюда,
        /// когда окно потащили, и из <see cref="WindowRaiser"/>, когда по
        /// окну просто нажали. Второе важнее первого и его-то и не было:
        /// тащить окно можно только за заголовок, а нажимают люди куда
        /// попало — по списку вещей, по кнопке, по пустому месту. Нижнее
        /// окно от такого нажатия оставалось внизу, и выглядело это как
        /// «подъём не работает вовсе».
        /// </summary>
        public static void BringToFront(Canvas canvas)
        {
            if (canvas == null) return;

            front++;
            if (front > FrontCap) front = FrontFrom + 1;
            canvas.sortingOrder = front;

            // И порядком в иерархии заодно. При равном sortingOrder решает
            // именно он, а холсты всех окон — соседи под одним объектом
            // игрока. Стоит дёшево и закрывает случай, когда два окна
            // оказались на одном номере.
            canvas.transform.SetAsLastSibling();
        }

        public void OnDrag(PointerEventData eventData)
        {
            if (target == null || !dragging) return;

            // Делим на масштаб холста: событие приходит в пикселях экрана, а
            // положение элемента живёт в единицах интерфейса. На мониторе с
            // другим разрешением окно иначе убегало бы от курсора.
            float scale = canvas != null ? canvas.scaleFactor : 1f;
            if (scale <= 0f) scale = 1f;

            // Копим точное положение отдельно, а окно ставим на ЦЕЛЫЙ пиксель.
            //
            // Мышь отдаёт дробные сдвиги, и окно накапливало полпикселя. Само
            // по себе это незаметно, но вся начинка съезжает вместе с ним: у
            // гнёзд кромка в один пиксель ложится между двумя, и с одной
            // стороны округляется вверх, с другой вниз. Павлон 04.09.2026:
            // «рамки имеют разную толщину обводки с четырёх сторон» — замер
            // подтвердил ровно это: слева и сверху два пикселя, справа и
            // снизу три. Пока окно стояло там, где его поставил сборщик,
            // кромка была ровная — портило её именно перетаскивание.
            //
            // Округляем на выводе, а копим точно: округляй само накопление —
            // и медленное движение мыши потеряет остаток, окно начнёт
            // отставать от курсора.
            exact += eventData.delta / scale;
            target.anchoredPosition = new Vector2(Mathf.Round(exact.x), Mathf.Round(exact.y));

            Clamp();

            // Упёрлись в край экрана — точное положение обязано догнать
            // обрезанное, иначе окно продолжит «ехать» в накоплении и
            // отлипнет от курсора рывком, когда мышь пойдёт обратно.
            exact = target.anchoredPosition;
        }

        /// <summary>
        /// Не даёт утащить окно за пределы экрана целиком.
        ///
        /// Считаем по настоящим углам окна, а не по формуле от центра холста.
        /// Прежняя формула исходила из того, что все окна привязаны к центру,
        /// — а окно персонажа привязано к левому верхнему углу. Для него
        /// предел ложился поперёк экрана: окно проезжало пару сотен пикселей
        /// и упиралось в невидимую стену примерно на середине. Со стороны это
        /// и выглядит как «окна не двигаются».
        ///
        /// Сдвиг считается в координатах холста и прибавляется к
        /// anchoredPosition напрямую: панель окна — прямой ребёнок своего
        /// холста, эти системы координат совпадают. То же допущение уже
        /// заложено в OnDrag.
        /// </summary>
        private void Clamp()
        {
            var canvasRect = canvas != null ? canvas.transform as RectTransform : null;
            if (canvasRect == null) return;

            target.GetWorldCorners(corners);

            for (int i = 0; i < 4; i++)
                corners[i] = canvasRect.InverseTransformPoint(corners[i]);

            // 0 — левый нижний, 1 — левый верхний, 2 — правый верхний.
            float left = corners[0].x;
            float right = corners[2].x;
            float bottom = corners[0].y;
            float top = corners[1].y;

            Rect area = canvasRect.rect;

            Vector2 shift = Vector2.zero;

            // Окно целиком внутри экрана — обе стороны сразу. Если окно шире
            // экрана, левый край побеждает: уехавший вправо правый край
            // человек хотя бы видит, а уехавший влево заголовок не поймать.
            if (right > area.xMax - ScreenPad) shift.x = area.xMax - ScreenPad - right;
            if (left + shift.x < area.xMin + ScreenPad)
                shift.x = area.xMin + ScreenPad - left;

            if (top > area.yMax - ScreenPad) shift.y = area.yMax - ScreenPad - top;
            if (bottom + shift.y < area.yMin + ScreenPad)
                shift.y = area.yMin + ScreenPad - bottom;

            if (shift != Vector2.zero)
                target.anchoredPosition += shift;
        }

        /// <summary>
        /// Делает окно перетаскиваемым и возвращает компонент.
        ///
        /// Вешается на САМУ панель, а не отдельной полосой поверх заголовка.
        /// Полоса была раньше и работала ровно до тех пор, пока её успевали
        /// поставить последней среди детей окна; стоило окну достроить
        /// содержимое после — и любой элемент накрывал ручку, забирая все
        /// нажатия себе. Разница видна снаружи как «одни окна двигаются,
        /// другие нет», а в коде не видна вовсе.
        ///
        /// Зовётся повторно без вреда: второй компонент на панель не ляжет.
        /// </summary>
        /// <param name="handleHeight">
        /// Тридцать пикселей — это полоса заголовка и ничего больше.
        ///
        /// Сорок, стоявшие тут сначала, залезали на первый ряд ячеек сумки:
        /// заголовок с отступом занимает тридцать четыре, и лишние шесть
        /// пикселей отняли бы у верхних ячеек часть площади нажатия.
        /// </param>
        /// <param name="overhang">
        /// На сколько видимый верх окна выступает над панелью.
        ///
        /// Нужно из-за нарисованной рамки: она кладётся ОТДЕЛЬНЫМ слоем
        /// снаружи панели и потому выступает за её край. Золотая кромка, за
        /// которую человек и хватается, оказывается выше панели — и без этой
        /// поправки живой осталась бы узкая полоска НИЖЕ золота, прямо под
        /// надписью заголовка, то есть там, где браться никто не станет.
        /// </param>
        public static DraggableWindow Attach(RectTransform panel,
                                             float handleHeight = 30f,
                                             float overhang = 0f)
        {
            if (panel == null) return null;

            var drag = panel.GetComponent<DraggableWindow>();
            if (drag == null) drag = panel.gameObject.AddComponent<DraggableWindow>();

            drag.Setup(panel, handleHeight, overhang);

            // Панель обязана ловить указатель, иначе перетаскивание молча не
            // работает — самая частая причина «код есть, а не двигается».
            // После ApplyFrame своя картинка панели прозрачна, но нажатия
            // принимает; окну без рамки картинку не заводим — там она своя.
            var image = panel.GetComponent<Image>();
            if (image != null) image.raycastTarget = true;

            return drag;
        }
    }
}
