using UnityEngine;

namespace IsoRPG.World
{
    /// <summary>
    /// Медленное вращение облачного кольца.
    ///
    /// У Synty кольца стоят неподвижно — на них нет ни одного компонента.
    /// Небо от этого мёртвое: в изометрии игрок часто стоит на месте, и
    /// застывшие облака читаются как нарисованный задник.
    ///
    /// Вращаем вокруг вертикали, а не двигаем: кольцо замкнуто, поэтому
    /// вращение идёт бесконечно и без стыка. Двум кольцам задаём разную
    /// скорость — разница даёт параллакс, и небо перестаёт быть плоским.
    ///
    /// Скорость намеренно крошечная. Облака, обходящие небо за минуту,
    /// читаются как карусель; настоящие проходят небосвод за десятки минут.
    /// </summary>
    public sealed class CloudDrift : MonoBehaviour
    {
        [Tooltip("Градусов в секунду. 0.3 — полный круг примерно за двадцать минут.")]
        public float degreesPerSecond = 0.3f;

        private void Update()
        {
            transform.Rotate(0f, degreesPerSecond * Time.deltaTime, 0f, Space.Self);
        }
    }
}
