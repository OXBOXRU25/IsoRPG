using UnityEngine;

namespace IsoRPG.World
{
    /// <summary>
    /// Держит челюсть закрытой.
    ///
    /// Павлон 02.09.2026, глядя на НПС: «почему у него рот открыт?» Потому что
    /// у скелета Sidekick есть кость `jaw`, а клипы нового набора её двигают:
    /// у автора персонаж в этих позах приоткрывает рот, и ретаргет честно
    /// переносит это на нашего. У прежнего набора челюсти в клипах не было
    /// вовсе, поэтому раньше мы этого не видели.
    ///
    /// Маской не лечится: у гуманоидного аватара челюсть входит в «голову»
    /// целиком, и выключить её отдельно нельзя — только вместе с кивками и
    /// поворотами головы, а они нужны.
    ///
    /// Поэтому замок на одну кость: запоминаем её поворот в покое и возвращаем
    /// после того, как отработал аниматор. Цена — одно присваивание в кадре на
    /// персонажа, ровно как у прижима к грунту. Мимики у нас всё равно нет, и
    /// когда появится — этот компонент снимается одной строкой.
    /// </summary>
    public sealed class JawLock : MonoBehaviour
    {
        [Tooltip("Имя кости челюсти в скелете.")]
        [SerializeField] private string boneName = "jaw";

        private Transform jaw;
        private Quaternion rest;

        private void Awake()
        {
            foreach (var t in GetComponentsInChildren<Transform>(true))
            {
                if (t.name != boneName) continue;

                jaw = t;
                rest = t.localRotation;
                break;
            }

            // Молчим: компонент общий, и у персонажа без челюсти он просто
            // ничего не делает — это законно, а не поломка.
            enabled = jaw != null;
        }

        // Именно LateUpdate: аниматор пишет кости в Update, и правка из
        // Update была бы им затёрта в том же кадре.
        private void LateUpdate() => jaw.localRotation = rest;
    }
}
