namespace IsoRPG.UI
{
    /// <summary>
    /// Общий рубильник нарисованных рамок интерфейса.
    ///
    /// Рамки — покупной арт: дерево с золотом у панели игрока, серый камень с
    /// красными трещинами у панели цели, отдельная плашка под рядом приёмов и
    /// собранная из деталей рама вокруг окон. По отдельности каждая деталь
    /// хороша, а вместе на экране они спорят: два разных материала рядом
    /// читаются как две разные игры, и обе рамы весят втрое больше того, что
    /// в них лежит.
    ///
    /// Поэтому не удаляем, а выключаем. Арт куплен и никуда не денется; когда
    /// наберём один комплект в одном материале — вернём одной строкой.
    ///
    /// Выключено — интерфейс собирается тем самым запасным путём, который в
    /// нём уже был на случай пропавших картинок: плоская плашка с тонкой
    /// светлой кромкой. Размеры панелей и координаты портретов при этом не
    /// меняются, поэтому ничего не разъезжается.
    /// </summary>
    public static class UiFrames
    {
        /// <summary>
        /// Рисовать ли покупные рамки. Выключено по решению от 27.08.2026.
        /// </summary>
        public static bool Enabled = false;
    }
}
