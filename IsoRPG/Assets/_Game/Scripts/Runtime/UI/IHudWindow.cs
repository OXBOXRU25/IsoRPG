namespace IsoRPG.UI
{
    /// <summary>
    /// Окно интерфейса, которое закрывается по Esc.
    ///
    /// Нужен ровно для одного: Esc должен открывать настройки, только если
    /// закрывать больше нечего. Без общего опроса каждое окно знало бы про Esc
    /// само по себе, и настройки выскакивали бы поверх закрывающейся сумки —
    /// одно нажатие, два разных действия.
    /// </summary>
    public interface IHudWindow
    {
        bool IsOpen { get; }

        void Close();
    }
}
