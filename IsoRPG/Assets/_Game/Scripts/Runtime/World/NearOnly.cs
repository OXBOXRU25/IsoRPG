using UnityEngine;

namespace IsoRPG.World
{
    /// <summary>
    /// Не рисует мелочь дальше заданного расстояния.
    ///
    /// Трава, цветы и ветки нужны под ногами и бессмысленны вдали: с сотни
    /// метров каждая травинка занимает меньше пикселя, и вместо зелени
    /// получается рябь из точек. Она особенно заметна на фоне неба у
    /// горизонта — именно её заказчик и назвал «белые точки и на земле, и на
    /// небе».
    ///
    /// Лечится не размером и не количеством, а пределом видимости: у камеры
    /// Unity он задаётся отдельно для каждого слоя. Мелочь живёт на своём
    /// слое, и дальше предела её просто нет — ни в кадре, ни в расчёте.
    ///
    /// Предел подняли с 45 до 70, а 02.09.2026 — до 140 метров.
    ///
    /// Семидесяти хватало только при близкой камере. Павлон: «часть цветов
    /// исчезает и появляется, когда камера далеко». Считаем: на дальнем зуме
    /// камера отходит на 26 метров, кадр захватывает ещё полсотни — дальний
    /// край уезжает за 80, и граница в 70 оказывается прямо в поле зрения.
    /// Пересекает её разом целая полоса растений на одном удалении, отсюда
    /// «пятнами».
    ///
    /// Мы искали это в уровнях детализации, мип-уровнях и тенях — а резал
    /// наш собственный предел видимости.
    ///
    /// Сто сорок уводят границу за дальний край кадра даже при полном
    /// отдалении. Рябь у горизонта, ради которой предел заводился, при этом
    /// не возвращается: её убирает уровень детализации, до неё дело доходит
    /// раньше.
    /// Заодно это самая дешёвая экономия кадров из возможных: пять тысяч
    /// объектов перестают обрабатываться, как только отошёл.
    ///
    /// Висит на камере, потому что предел — свойство камеры, а не объектов.
    /// </summary>
    [RequireComponent(typeof(Camera))]
    public sealed class NearOnly : MonoBehaviour
    {
        [Tooltip("Слой, который прячем вдали.")]
        public string Layer = "Detail";

        [Tooltip("Дальше этого расстояния слой не рисуется, метров.")]
        public float Distance = 140f;

        private void OnEnable() => Apply();

        private void Apply()
        {
            var camera = GetComponent<Camera>();
            if (camera == null) return;

            int layer = LayerMask.NameToLayer(Layer);

            if (layer < 0)
            {
                // Слоя нет — молчать нельзя: без него мелочь рисуется до
                // горизонта, и та самая рябь возвращается, а причина
                // выглядит необъяснимой.
                Debug.LogWarning("[IsoRPG] Нет слоя «" + Layer +
                                 "» — мелочь будет рисоваться до горизонта.");
                return;
            }

            // Массив задаётся целиком: тронуть один элемент нельзя, Unity
            // отдаёт копию.
            var limits = camera.layerCullDistances;
            limits[layer] = Distance;
            camera.layerCullDistances = limits;

            // Сферическое отсечение, а не по плоскости: иначе трава сбоку
            // пропадает раньше, чем прямо по курсу, и край видимости
            // становится заметен при повороте камеры.
            camera.layerCullSpherical = true;
        }
    }
}
