using UnityEditor;
using UnityEditor.Rendering.Universal;
using UnityEngine;

namespace IsoRPG.EditorTools
{
    /// <summary>
    /// Запускает ОФИЦИАЛЬНЫЙ конвертер Unity: встроенный конвейер → URP.
    ///
    /// Это замена моему самописному переводу материалов, и замена вынужденная.
    /// Мой знал ровно то, что я в него вписал: перенеси текстуру отсюда сюда,
    /// погаси блеск, включи прозрачность. Каждое такое правило — догадка,
    /// применённая к тысяче с лишним материалов разом, и за вечер три из пяти
    /// догадок сделали хуже: камни ушли в металл, деревья побелели, у листвы
    /// сломалось растворение.
    ///
    /// Официальный конвертер знает таблицу соответствий для каждого
    /// встроенного шейдера: какое свойство куда ложится, что делать с
    /// прозрачностью, глянцем и картами нормалей. Знать это самому неоткуда.
    ///
    /// Обычно его открывают меню (Window → Rendering → Render Pipeline
    /// Converter), но у него есть и пакетный вызов — он для того и сделан,
    /// чтобы гонять в сборочных машинах. Значит человеку кликать не надо.
    ///
    /// <b>Важно про порядок.</b> Конвертер трогает только те материалы, что
    /// ещё сидят на встроенных шейдерах. Уже переведённые — в том числе
    /// испорченные мной — он пропустит как готовые. Поэтому наборы, которые
    /// я успел испортить, надо СНАЧАЛА переустановить начисто, и только потом
    /// звать его.
    /// </summary>
    public static class OfficialConvert
    {
        [MenuItem("Tools/IsoRPG/Материалы: официальный конвертер URP", priority = 6)]
        public static void Run()
        {
            Debug.Log("[IsoRPG] Запускаю официальный конвертер Unity: " +
                      "встроенный конвейер → URP. Это может занять минуты.");

            Converters.RunInBatchMode(ConverterContainerId.BuiltInToURP);

            AssetDatabase.SaveAssets();
            AssetDatabase.Refresh();

            Debug.Log("[IsoRPG] Официальный конвертер отработал.");
        }
    }
}
