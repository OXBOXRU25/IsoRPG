using UnityEngine;

namespace IsoRPG.World
{
    /// <summary>
    /// Держит купол неба на камере.
    ///
    /// Купол — это большая сфера с текстурой изнутри. Стоит она в мире, а не
    /// в настройках сцены, и поэтому у неё есть положение: отойди от неё —
    /// и увидишь её край. Лечится одним движением: каждый кадр ставим купол в
    /// точку камеры. Тогда до горизонта всегда одинаково далеко, как и должно
    /// быть у неба.
    ///
    /// Высоту не копируем.
    ///
    /// Причина тонкая: если купол ездит за камерой и по вертикали, линия
    /// горизонта прилипает к взгляду и перестаёт быть горизонтом — при
    /// подъёме камеры земля и небо начинают двигаться одинаково, и пропадает
    /// ощущение, что мир внизу. Оставляем купол на уровне земли: он
    /// достаточно велик, чтобы вертикального смещения камеры не хватило
    /// увидеть его край.
    ///
    /// В LateUpdate, а не в Update: камера двигается в LateUpdate, и купол,
    /// поставленный раньше неё, отстаёт на кадр. На быстрой пробежке это
    /// видно как дрожание горизонта.
    /// </summary>
    [ExecuteAlways]
    public sealed class SkyDomeFollow : MonoBehaviour
    {
        private Transform eye;

        private void LateUpdate()
        {
            if (eye == null)
            {
                var camera = Camera.main;
                if (camera == null) return;

                eye = camera.transform;
            }

            var at = eye.position;
            transform.position = new Vector3(at.x, transform.position.y, at.z);
        }
    }
}
